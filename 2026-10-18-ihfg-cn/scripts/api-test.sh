#!/bin/bash
# 端到端 API 闭环测试(12 场景)
CJ="/tmp/ihfg-local-cj.txt"
rm -f "$CJ"
B="http://localhost:3000"

echo "=== 1.会话检查(未登录) ==="
curl -sL -c "$CJ" "$B/api/auth/session"; echo ""
echo "=== 2.注册 ==="
curl -sL -b "$CJ" -c "$CJ" -X POST "$B/api/auth/register" -H "Content-Type: application/json" -d '{"username":"demo","email":"demo@test.com","password":"abc123","firstname":"三","lastname":"张","phone":"13800000000"}'; echo ""
echo "=== 3.重复注册(应EXIST) ==="
curl -sL -X POST "$B/api/auth/register" -H "Content-Type: application/json" -d '{"username":"demo","email":"demo@test.com","password":"abc123","firstname":"三","lastname":"张","phone":"138"}'; echo ""
echo "=== 4.加购第1件 ==="
curl -sL -b "$CJ" -c "$CJ" -X POST "$B/api/shopping-cart/add" -F "fileId=demo-1BR-BA-20-I" -F "code=1BR-BA-20-I"; echo ""
echo "=== 5.重复加购同件(应仍为1,去重) ==="
curl -sL -b "$CJ" -c "$CJ" -X POST "$B/api/shopping-cart/add" -F "fileId=demo-1BR-BA-20-I" -F "code=1BR-BA-20-I"; echo ""
echo "=== 6.加购第2件(应为2) ==="
curl -sL -b "$CJ" -c "$CJ" -X POST "$B/api/shopping-cart/add" -F "fileId=demo-OR-GN-I" -F "code=OR-GN-I"; echo ""
echo "=== 7.购物车查询 ==="
curl -sL -b "$CJ" "$B/api/shopping-cart"; echo ""
echo "=== 8.错误密码登录(应INVALID_CREDENTIALS) ==="
curl -sL -X POST "$B/api/auth/login" -H "Content-Type: application/json" -d '{"username":"demo","password":"wrong"}'; echo ""
echo "=== 9.正确登录 ==="
curl -sL -c "$CJ" -X POST "$B/api/auth/login" -H "Content-Type: application/json" -d '{"username":"demo","password":"abc123"}'; echo ""
echo "=== 10.会话检查(已登录) ==="
curl -sL -b "$CJ" "$B/api/auth/session"; echo ""
echo "=== 11.组件API(搜索+分页) ==="
curl -sL "$B/api/components?q=operating%20room&size=2" | head -c 260; echo ""
echo "=== 12.分享 ==="
curl -sL -X POST "$B/api/share/email" -F "name=Test Item" -F "email=a@b.com" -F "code=1BR-BA-20-I"; echo ""
echo "=== 13.逆向详情API(MRI) ==="
curl -sL "$B/api/components/MRI-Scanning-Room-42m2" | head -c 260; echo ""
